#!/usr/bin/env node
// hr27-lines-check.mjs — dependency-freies HR27-Zeilen-Gate (B14).
//
// Prueft Datei-Zeilenlimits (HR27) ohne irgendetwas aus src/ zu importieren
// (.mjs kann das TS-Modul nicht laden). Limits und Skip-Liste stehen als
// Single-Source in scripts/hr27-lines-baseline.json; ein Cross-Test
// (tests/write/hr27-lines-check.spec.ts) pinnt sie gegen HR27_LIMITS und
// HR27_SKIP_DIRS aus src/main/scan/hr27-scan.ts — bewusste Duplikation,
// aber gegengeprueft, kein drittes Divergenz-Risiko.
//
// Verzicht (dokumentiert): Das HR27-Funktions-Limit (50 Zeilen) wird hier
// NICHT geprueft. Eine regex-/einrueckungsbasierte Heuristik erzeugt bei
// Arrow-Chains, Klassen und Objekt-Literalen zu viele Falschpositive fuer
// ein hartes Gate im verify-Pfad; das Datei-Limit bleibt der belastbare
// mechanische Check, Funktionslaenge bleibt Review-/Scanner-Thema.
//
// Baseline-Semantik: Verletzungen, die in knownViolations eingetragen sind,
// warnen nur (Exit 0). NEUE Verletzungen schlagen fehl (Exit 1).
// Baseline neu schreiben: node scripts/hr27-lines-check.mjs --write-baseline
// (wird von der Hauptsession in WP-7 nach den Parallel-Splits regeneriert).
//
// Aufruf: node scripts/hr27-lines-check.mjs [--root <dir>] [--baseline <path>] [--write-baseline]
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url))
const DEFAULT_ROOT = path.resolve(SCRIPT_DIR, '..')
const DEFAULT_BASELINE = path.join(SCRIPT_DIR, 'hr27-lines-baseline.json')

// Spiegel von hr27-scan.ts (Datei-/Marker-Regeln, dort PLAN_RX/GENERATED_RX).
const PLAN_RX = /^(PLAN|COMPLETED_PLAN|SUPERSEDED_PLAN|WIP_PLAN|DRAFT_PLAN)-.*\.md$/i
const GENERATED_RX = /auto-generated|@generated|generated by|this file is generated/i
const HINWEIS =
  'HR27-Gate-Config: limits/skipDirs sind Single-Source fuer hr27-lines-check.mjs und per Cross-Test ' +
  '(tests/write/hr27-lines-check.spec.ts) gegen src/main/scan/hr27-scan.ts gepinnt. knownViolations = ' +
  'bekannte Ist-Verletzungen (warn). Regenerieren: node scripts/hr27-lines-check.mjs --write-baseline ' +
  '(Hauptsession, WP-7). Stale Eintraege nach Splits sind harmlos.'

function parseArgs(argv) {
  const opts = { root: DEFAULT_ROOT, baseline: DEFAULT_BASELINE, writeBaseline: false }
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i] === '--root') opts.root = path.resolve(argv[++i])
    else if (argv[i] === '--baseline') opts.baseline = path.resolve(argv[++i])
    else if (argv[i] === '--write-baseline') opts.writeBaseline = true
    else {
      console.error(`Unbekanntes Argument: ${argv[i]}`)
      process.exit(2)
    }
  }
  return opts
}

function loadBaseline(file) {
  try {
    const data = JSON.parse(fs.readFileSync(file, 'utf8'))
    if (!data.limits || !data.skipDirs || !data.knownViolations) throw new Error('Struktur unvollstaendig')
    return data
  } catch (err) {
    console.error(`Baseline nicht lesbar: ${file} (${err.message})`)
    process.exit(2)
  }
}

// Walk + Scan spiegeln scanHr27 aus src/main/scan/hr27-scan.ts (gleiche
// Zeilenzaehlung, gleiche Skip-Regeln), damit Gate und In-App-Audit uebereinstimmen.
function collectViolations(root, limits, skipDirs) {
  const findings = []
  const skip = new Set(skipDirs.map((d) => d.toLowerCase()))
  walk(root, root, limits, skip, findings)
  return findings.sort((a, b) => a.rel.localeCompare(b.rel))
}

function walk(root, dir, limits, skip, findings) {
  let entries
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true })
  } catch {
    return
  }
  for (const entry of entries) {
    const abs = path.join(dir, entry.name)
    if (entry.isDirectory()) {
      if (!shouldSkipDir(root, abs, entry.name, skip)) walk(root, abs, limits, skip, findings)
    } else if (entry.isFile()) {
      scanFile(root, abs, limits, findings)
    }
  }
}

function shouldSkipDir(root, abs, name, skip) {
  if (skip.has(name.toLowerCase())) return true
  const rel = toRel(root, abs).toLowerCase()
  return rel === 'docs' || rel.startsWith('docs/')
}

function scanFile(root, abs, limits, findings) {
  const ext = path.extname(abs).slice(1).toLowerCase()
  const limit = limits[ext]
  if (!limit) return
  const base = path.basename(abs)
  if (base.toLowerCase() === 'memory.md' || PLAN_RX.test(base)) return
  let text
  try {
    text = fs.readFileSync(abs, 'utf8')
  } catch {
    return
  }
  if (GENERATED_RX.test(text.slice(0, 4096))) return
  const lines = countLines(text)
  if (lines <= limit) return
  findings.push({ rel: toRel(root, abs), lines, limit })
}

function countLines(text) {
  if (text.length === 0) return 0
  const normalized = text.endsWith('\n') ? text.slice(0, -1) : text
  return normalized.length === 0 ? 1 : normalized.split(/\r?\n/).length
}

function toRel(root, abs) {
  return (path.relative(root, abs) || '.').replace(/\\/g, '/')
}

function main() {
  const opts = parseArgs(process.argv.slice(2))
  const baseline = loadBaseline(opts.baseline)
  const findings = collectViolations(opts.root, baseline.limits, baseline.skipDirs)

  if (opts.writeBaseline) {
    const known = {}
    for (const f of findings) known[f.rel] = { lines: f.lines, limit: f.limit }
    const next = { hinweis: HINWEIS, limits: baseline.limits, skipDirs: baseline.skipDirs, knownViolations: known }
    fs.writeFileSync(opts.baseline, `${JSON.stringify(next, null, 2)}\n`, 'utf8')
    console.log(`Baseline geschrieben: ${opts.baseline} (${findings.length} bekannte Verletzungen)`)
    process.exit(0)
  }

  const known = baseline.knownViolations
  const fresh = []
  const seen = new Set()
  for (const f of findings) {
    if (Object.prototype.hasOwnProperty.call(known, f.rel)) {
      seen.add(f.rel)
      console.warn(`WARN bekannte HR27-Verletzung: ${f.rel} (${f.lines}/${f.limit} Zeilen)`)
    } else {
      fresh.push(f)
    }
  }
  for (const rel of Object.keys(known)) {
    if (!seen.has(rel)) console.log(`Info: Baseline-Eintrag stale (jetzt im Limit oder weg): ${rel}`)
  }
  if (fresh.length > 0) {
    for (const f of fresh) {
      console.error(`NEUE HR27-Verletzung: ${f.rel} (${f.lines}/${f.limit} Zeilen) — Datei splitten (HR27)`)
    }
    console.error(`${fresh.length} neue Verletzung(en). Gate fehlgeschlagen.`)
    process.exit(1)
  }
  console.log(`HR27-Zeilen-Gate ok: ${findings.length} bekannte Verletzung(en), keine neuen.`)
  process.exit(0)
}

main()
